/// Strongest commercial position for Letters to Heaven.
///
/// Market a private rescue net for memories—not a grief program, therapist
/// substitute, or digital reprint of a long paper journal.
abstract final class CommercialPosition {
  /// Brand-level market claim.
  static const marketAs =
      'The private place that catches a memory before it disappears.';

  /// Best headline (store, marketing, hero).
  static const headline =
      'Save the little things before time carries them away.';

  /// Best supporting line.
  static const supporting =
      'Write what you still wish you could say. Preserve the stories, photos, '
      'voices, recipes, signs, and ordinary details you never want to lose.';

  /// Best subscription promise ($4.99/mo).
  static const subscriptionPromise =
      'For \$4.99 a month, your memories are privately backed up, easy to find, '
      'rich with photos and voices, and ready to become a keepsake whenever '
      'you choose.';

  static const productShape =
      'Feel less like a grief program and more like a beautiful, private '
      'rescue net for memories that arrive without warning.';

  static const premiumReason =
      'Keepsake creation—backed-up photos, voices, and a book when you are ready—'
      'is the clearest reason to subscribe.';

  /// Do not market the product as these.
  static const doNotMarketAs = <String>[
    'A large collection of grief prompts',
    'A cheaper therapist',
    'A digital version of a 213-page journal',
  ];

  /// Product shape recommendations that support the commercial position.
  static const productRecommendations = <String>[
    'Keep the emotional foundation and privacy rules from the PRD',
    'Cut the number of visible choices',
    'Move account creation until after the first saved memory',
    'Place voice and quick capture at the center',
    'Make keepsake creation the premium reason to subscribe',
  ];
}
